-- Operational source of truth (schema `oltp`). Written by the transaction
-- simulator, read by the ETL and by the read-only investigation tools.
--
-- Every table carries `updated_at`, stamped on insert and on every change.
-- The ETL uses it as its high-water mark.

CREATE SCHEMA IF NOT EXISTS oltp;

CREATE TABLE IF NOT EXISTS oltp.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- order_status: CREATED | PAID | CANCELLED | PARTIALLY_REFUNDED | REFUNDED
CREATE TABLE IF NOT EXISTS oltp.orders (
    order_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT NOT NULL REFERENCES oltp.customers (customer_id),
    order_status TEXT NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    currency     CHAR(3) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- payment_status: CAPTURED | FAILED
CREATE TABLE IF NOT EXISTS oltp.payments (
    payment_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT NOT NULL REFERENCES oltp.orders (order_id),
    payment_status TEXT NOT NULL,
    amount         NUMERIC(12, 2) NOT NULL,
    paid_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- refund_status: PENDING | SUCCEEDED | FAILED
CREATE TABLE IF NOT EXISTS oltp.refunds (
    refund_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id    BIGINT NOT NULL REFERENCES oltp.payments (payment_id),
    order_id      BIGINT NOT NULL REFERENCES oltp.orders (order_id),
    refund_status TEXT NOT NULL,
    refund_amount NUMERIC(12, 2) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS orders_updated_at_idx ON oltp.orders (updated_at, order_id);
CREATE INDEX IF NOT EXISTS payments_updated_at_idx ON oltp.payments (updated_at, payment_id);
CREATE INDEX IF NOT EXISTS payments_order_idx ON oltp.payments (order_id);
CREATE INDEX IF NOT EXISTS refunds_updated_at_idx ON oltp.refunds (updated_at, refund_id);
CREATE INDEX IF NOT EXISTS refunds_order_idx ON oltp.refunds (order_id);
